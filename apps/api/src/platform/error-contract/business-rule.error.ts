/**
 * رد یک عملیات به‌خاطر قاعده‌ی کسب‌وکار که کاربر می‌تواند اصلاحش کند — M-09.
 *
 * نمونه‌ها: موجودی کافی نیست، مبلغ پرداختی از مبلغ فاکتور بیشتر است، فاکتور هنوز نهایی
 * نشده. این‌ها نه ۵۰۰ هستند (سامانه خراب نیست) نه ۴۰۹ (تغییر هم‌زمان داده نیست) و نه
 * ۴۰۰ ِ اعتبارسنجی (شکل ورودی درست است). پیش‌تر هر controller باید خودش ترجمه‌شان
 * می‌کرد و چند تا جا مانده بودند — فروش کالای ناموجود (#45) و خطاهای اصلاحیه (#54) ۵۰۰
 * «خطای غیرمنتظره» می‌دادند. حالا filter سراسری همه را یکجا می‌شناسد.
 *
 * `message` همان پیام فنی (انگلیسی) برای log و تست می‌ماند؛ `userMessage` ِ فارسی است
 * که به کاربر می‌رسد و نباید شناسه یا جزئیات داخلی داشته باشد.
 */
export abstract class BusinessRuleError extends Error {
  protected constructor(
    technicalMessage: string,
    readonly userMessage: string,
  ) {
    super(technicalMessage);
  }
}

/** کد پایدار پاسخ — فرانت پیام سرور را فقط برای همین کد نشان می‌دهد. */
export const BUSINESS_RULE_ERROR_CODE = 'BUSINESS_RULE_VIOLATION';
