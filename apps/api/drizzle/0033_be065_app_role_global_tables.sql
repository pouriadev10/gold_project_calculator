-- BE-065 — نقش برنامه به جدول‌های سراسری دست نمی‌زند.
--
-- مهاجرت ۰۰۰۳ به `gold_app` روی «همه‌ی جدول‌ها» دسترسی DML داد. جدول‌های
-- داده‌ی مستأجر با RLS محافظت می‌شوند، ولی جدول‌های سراسری RLS ندارند:
-- `tenants`، `users`، `refresh_tokens`، `roles` و `migration_probes`. یعنی
-- SQL‌ای که با نقش برنامه و مستأجر الف اجرا می‌شد می‌توانست هش رمز و هش توکن
-- کاربران مستأجر ب را بخواند یا مستأجر ب را معلق کند — دقیقاً همان مسیری که
-- RLS قرار بود ببندد. (بدهی صریح BE-009: «بستن کامل این شکاف کار BE-065 است».)
--
-- برنامه به این جدول‌ها فقط با اتصال اصلی (خارج از `withTenantTransaction`)
-- دست می‌زند: ورود، توکن تمدید، ساخت مستأجر، صادرکننده‌ی PDF. داخل تراکنش
-- مستأجر تنها نیاز، نام نمایشی سازنده‌ی سند است (تاریخچه‌ی فاکتور)، پس فقط
-- همان دو ستون باز می‌ماند. بررسی کلید خارجی با مالک جدول اجرا می‌شود و به
-- این دسترسی‌ها نیازی ندارد.
REVOKE ALL ON TABLE tenants, users, refresh_tokens, roles, migration_probes FROM gold_app;
